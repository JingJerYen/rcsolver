/**
 * Offline: find short move sequences that leave the centres alone and move only a few wings.
 * Run with `npx tsx scripts/gen-macros.ts`; writes web/src/solvers/cube4macros.ts.
 */
import { writeFileSync } from "node:fs";
import { applyAlgorithm, fromNet, parseAlgorithm } from "../web/src/cubeState.js";
import { OUTER_MOVES } from "../web/src/solvers/cube4centers.js";
import { WING_POS, centresUniform, sequencePerm } from "../web/src/solvers/cube4edges.js";
import type { Face } from "../web/src/api.js";

const COLORS: Record<Face, string> = { U: "W", R: "R", F: "G", D: "Y", L: "O", B: "B" };
const solvedNet = Object.fromEntries((Object.keys(COLORS) as Face[]).map((f) => [f, Array.from({ length: 4 }, () => COLORS[f].repeat(4))])) as Record<Face, string[]>;
const solved = fromNet(4, solvedNet);

const SLICE_Q = ["2U", "2U'", "2D", "2D'", "2R", "2R'", "2L", "2L'", "2F", "2F'", "2B", "2B'"];
const inverse = (t: string) => (t.endsWith("'") ? t.slice(0, -1) : t.endsWith("2") ? t : `${t}'`);
const faceOf = (t: string) => t.replace(/[2']/g, "").replace(/^\d/, "");

function outerSeqs(maxLen: number): string[][] {
  const out: string[][] = [];
  const rec = (seq: string[]) => {
    if (seq.length) out.push(seq);
    if (seq.length === maxLen) return;
    for (const m of OUTER_MOVES) {
      if (seq.length && faceOf(seq[seq.length - 1]!) === faceOf(m)) continue;
      rec([...seq, m]);
    }
  };
  rec([]);
  return out;
}

const best = new Map<string, string[]>(); // perm key -> shortest tokens
let tested = 0;
function consider(tokens: string[]) {
  tested++;
  const perm = sequencePerm(tokens);
  let moved = 0;
  for (let i = 0; i < 24; i++) if (perm[i] !== i) moved++;
  if (moved === 0 || moved > 4) return;
  const cube = applyAlgorithm(solved, parseAlgorithm(tokens.join(" "), 4));
  if (!centresUniform(cube)) return;
  const k = Array.from(perm).join(",");
  const prev = best.get(k);
  if (!prev || prev.length > tokens.length) best.set(k, tokens);
}

const X = outerSeqs(3);
for (const s of SLICE_Q) {
  for (const x of X) {
    // commutator s X s' X'
    consider([s, ...x, inverse(s), ...x.slice().reverse().map(inverse)]);
    // sandwich s X t
    for (const t of SLICE_Q) consider([s, ...x, t]);
  }
}
// well-known algorithms, in case the search misses them
for (const alg of [
  "2D R F' U R' F 2D'",
  "2U' R U R' F R' F' R 2U",
  "Rw2 B2 U2 Lw U2 Rw' U2 Rw U2 F2 Rw F2 Lw' B2 Rw2",
  "2R2 U2 2R2 Uw2 2R2 2U2",
  "Rw2 U2 Rw2 Uw2 Rw2 Uw2",
]) consider(alg.split(" "));

// The last two edges need a 3-cycle that touches both wings of one slot; none of the short
// sequences does that, but the product of two 3-cycles can.
const WING_SLOT = WING_POS.map((w) => w.slot);
const threeCycles = [...best.values()].map((t) => ({ t, p: sequencePerm(t) })).filter(({ p }) => Array.from(p).filter((v, i) => v !== i).length === 3);
const compose = (a: Uint8Array, b: Uint8Array) => a.map((v) => b[v]!);
for (const A of threeCycles) {
  for (const B of threeCycles) {
    const p = compose(A.p, B.p);
    const moved = Array.from(p).map((v, i) => (v !== i ? i : -1)).filter((i) => i >= 0);
    if (moved.length !== 3 || new Set(moved.map((i) => WING_SLOT[i])).size === 3) continue;
    const k = Array.from(p).join(",");
    const tokens = [...A.t, ...B.t];
    const prev = best.get(k);
    if (!prev || prev.length > tokens.length) best.set(k, tokens);
  }
}

const macros = [...best.values()].sort((a, b) => a.length - b.length);
const stats = { tested, kept: macros.length, byMoved: {} as Record<number, number> };
for (const m of macros) {
  const perm = sequencePerm(m);
  let moved = 0;
  for (let i = 0; i < 24; i++) if (perm[i] !== i) moved++;
  stats.byMoved[moved] = (stats.byMoved[moved] ?? 0) + 1;
}
console.log(stats);
writeFileSync(
  "web/src/solvers/cube4macros.ts",
  `// Generated by scripts/gen-macros.ts: centre-preserving sequences that move at most 4 wings.\nexport const MACROS: string[][] = ${JSON.stringify(macros)};\n`,
);
